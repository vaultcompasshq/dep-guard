import { isPythonLockfilePath, parsePythonLockfile } from '../src/python-lockfiles.js';

function lines(text: string[]): string {
  return `${text.join('\n')}\n`;
}

function summary(path: string, content: string) {
  const parsed = parsePythonLockfile(path, content);
  return {
    unreadable: parsed.unreadable,
    entries: parsed.entries.map((entry) => [entry.name, entry.version, entry.source]),
  };
}

describe('isPythonLockfilePath', () => {
  test.each(['poetry.lock', 'apps/x/uv.lock', 'pdm.lock', 'Pipfile.lock'])('%s is a Python lockfile', (path) => {
    expect(isPythonLockfilePath(path)).toBe(true);
  });
  test.each(['package-lock.json', 'requirements.lock', 'uv.lock.bak'])('%s is not', (path) => {
    expect(isPythonLockfilePath(path)).toBe(false);
  });
});

describe('poetry.lock', () => {
  test('names, versions and source classes from a real-shaped file', () => {
    const content = lines([
      '# This file is automatically @generated by Poetry 1.8.3 and should not be changed by hand.',
      '',
      '[[package]]',
      'name = "Requests"',
      'version = "2.31.0"',
      'description = "Python HTTP for Humans."',
      'optional = false',
      'python-versions = ">=3.7"',
      'files = [',
      '    {file = "requests-2.31.0-py3-none-any.whl", hash = "sha256:aa"},',
      ']',
      '',
      '[package.dependencies]',
      'idna = ">=2.5,<4"',
      '',
      '[[package]]',
      'name = "corp-lib"',
      'version = "1.0.0"',
      'description = ""',
      'optional = false',
      'python-versions = "*"',
      'files = []',
      '',
      '[package.source]',
      'type = "legacy"',
      'url = "https://private.example/simple"',
      'reference = "corp"',
      '',
      '[[package]]',
      'name = "gitdep"',
      'version = "0.1.0"',
      'description = ""',
      'optional = false',
      'python-versions = "*"',
      'files = []',
      '',
      '[package.source]',
      'type = "git"',
      'url = "https://example.com/gitdep.git"',
      'reference = "HEAD"',
      'resolved_reference = "abc"',
      '',
      '[[package]]',
      'name = "localdep"',
      'version = "0.1.0"',
      'description = ""',
      'optional = false',
      'python-versions = "*"',
      'files = []',
      'develop = true',
      '',
      '[package.source]',
      'type = "directory"',
      'url = "libs/localdep"',
      '',
      '[metadata]',
      'lock-version = "2.0"',
      'python-versions = "^3.11"',
      'content-hash = "x"',
    ]);
    expect(summary('poetry.lock', content)).toEqual({
      unreadable: undefined,
      entries: [
        ['requests', '2.31.0', { kind: 'pypi' }],
        ['corp-lib', '1.0.0', { kind: 'index', origin: 'https://private.example/simple' }],
        ['gitdep', '0.1.0', { kind: 'excluded', cls: 'vcs' }],
        ['localdep', '0.1.0', { kind: 'excluded', cls: 'editable' }],
      ],
    });
  });

  test('a malformed file is unreadable', () => {
    expect(summary('poetry.lock', '[[package]\nname = "x"\n').unreadable).toBeDefined();
    expect(summary('poetry.lock', lines(['[[package]]', 'version = "1"'])).unreadable).toBeDefined();
  });
});

describe('uv.lock', () => {
  test('names, versions and source classes from a real-shaped file', () => {
    const content = lines([
      'version = 1',
      'requires-python = ">=3.9"',
      '',
      '[[package]]',
      'name = "blinker"',
      'version = "1.8.2"',
      'source = { registry = "https://pypi.org/simple" }',
      'sdist = { url = "https://files.pythonhosted.org/x.tar.gz", hash = "sha256:aa", size = 1 }',
      '',
      '[[package]]',
      'name = "flask"',
      'version = "3.1.0.dev0"',
      'source = { editable = "." }',
      '',
      '[[package]]',
      'name = "corp"',
      'version = "1.0"',
      'source = { registry = "https://private.example/simple" }',
      '',
      '[[package]]',
      'name = "member"',
      'version = "0.1"',
      'source = { virtual = "packages/member" }',
      '',
      '[[package]]',
      'name = "g"',
      'version = "0.1"',
      'source = { git = "https://example.com/g.git?rev=abc#abc" }',
      '',
      '[[package]]',
      'name = "u"',
      'version = "0.1"',
      'source = { url = "https://example.com/u.whl" }',
      '',
      '[[package]]',
      'name = "d"',
      'version = "0.1"',
      'source = { directory = "libs/d" }',
    ]);
    expect(summary('uv.lock', content).entries).toEqual([
      ['blinker', '1.8.2', { kind: 'pypi' }],
      ['flask', '3.1.0.dev0', { kind: 'excluded', cls: 'path' }],
      ['corp', '1.0', { kind: 'index', origin: 'https://private.example/simple' }],
      ['member', '0.1', { kind: 'excluded', cls: 'path' }],
      ['g', '0.1', { kind: 'excluded', cls: 'vcs' }],
      ['u', '0.1', { kind: 'excluded', cls: 'url' }],
      ['d', '0.1', { kind: 'excluded', cls: 'path' }],
    ]);
  });

  test('a registry source naming PyPI with a trailing slash is PyPI', () => {
    const content = lines(['version = 1', '[[package]]', 'name = "a"', 'version = "1"', 'source = { registry = "https://pypi.org/simple/" }']);
    expect(summary('uv.lock', content).entries).toEqual([['a', '1', { kind: 'pypi' }]]);
  });

  test('an entry with no recognised source shape is unreadable, never a silent skip', () => {
    const content = lines(['version = 1', '[[package]]', 'name = "a"', 'version = "1"', 'source = { frob = "x" }']);
    expect(summary('uv.lock', content).unreadable).toBeDefined();
  });
});

describe('pdm.lock', () => {
  test('names and source classes from a real-shaped file', () => {
    const content = lines([
      '# This file is @generated by PDM.',
      '[metadata]',
      'groups = ["default"]',
      'strategy = ["inherit_metadata"]',
      'lock_version = "4.5.0"',
      'content_hash = "sha256:aa"',
      '',
      '[[package]]',
      'name = "requests"',
      'version = "2.31.0"',
      'requires_python = ">=3.7"',
      'summary = "Python HTTP for Humans."',
      'groups = ["default"]',
      'files = [',
      '    {file = "requests-2.31.0-py3-none-any.whl", hash = "sha256:aa"},',
      ']',
      '',
      '[[package]]',
      'name = "vcsdep"',
      'version = "0.1"',
      'git = "https://example.com/v.git"',
      'revision = "abc"',
      'summary = ""',
      '',
      '[[package]]',
      'name = "localdep"',
      'version = "0.1"',
      'path = "./libs/localdep"',
      'editable = true',
      'summary = ""',
    ]);
    expect(summary('pdm.lock', content).entries).toEqual([
      ['requests', '2.31.0', { kind: 'pypi' }],
      ['vcsdep', '0.1', { kind: 'excluded', cls: 'vcs' }],
      ['localdep', '0.1', { kind: 'excluded', cls: 'editable' }],
    ]);
  });

  test('an unrecognised entry shape is unreadable', () => {
    expect(summary('pdm.lock', lines(['[[package]]', 'name = 3'])).unreadable).toBeDefined();
  });
});

describe('Pipfile.lock', () => {
  const lock = (meta: unknown[], entries: Record<string, unknown>): string =>
    JSON.stringify({ _meta: { sources: meta, 'pipfile-spec': 6 }, default: entries, develop: {} });

  test('names, versions and source classes from a real-shaped file', () => {
    const content = lock(
      [
        { name: 'pypi', url: 'https://pypi.org/simple', verify_ssl: true },
        { name: 'corp', url: 'https://private.example/simple', verify_ssl: true },
      ],
      {
        requests: { hashes: ['sha256:aa'], index: 'pypi', version: '==2.31.0' },
        'corp-lib': { hashes: [], index: 'corp', version: '==1.0' },
        gitdep: { git: 'https://example.com/g.git', ref: 'abc' },
        localdep: { editable: true, path: '.' },
      }
    );
    expect(summary('Pipfile.lock', content).entries).toEqual([
      ['requests', '2.31.0', { kind: 'pypi' }],
      ['corp-lib', '1.0', { kind: 'index', origin: 'https://private.example/simple' }],
      ['gitdep', null, { kind: 'excluded', cls: 'vcs' }],
      ['localdep', null, { kind: 'excluded', cls: 'editable' }],
    ]);
  });

  test('_meta.sources remapping the pypi index name to another host is that host, not PyPI', () => {
    const content = lock([{ name: 'pypi', url: 'https://evil.example/simple' }], {
      requests: { index: 'pypi', version: '==2.31.0' },
    });
    expect(summary('Pipfile.lock', content).entries).toEqual([
      ['requests', '2.31.0', { kind: 'index', origin: 'https://evil.example/simple' }],
    ]);
  });

  test('a file that is not JSON is unreadable', () => {
    expect(summary('Pipfile.lock', '{not json').unreadable).toBeDefined();
  });
});

describe('lockfile names go through the name pattern', () => {
  test('an invalid name is recorded, not looked up', () => {
    const content = lines(['version = 1', '[[package]]', 'name = "café"', 'version = "1"', 'source = { registry = "https://pypi.org/simple" }']);
    const parsed = parsePythonLockfile('uv.lock', content);
    expect(parsed.entries).toEqual([]);
    // Only the leading name characters are kept for display (B2).
    expect(parsed.invalidNames).toEqual(['caf...']);
  });
});
